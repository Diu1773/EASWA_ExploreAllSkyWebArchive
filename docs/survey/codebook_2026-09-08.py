def tally(rows):
    unit, person = defaultdict(int), defaultdict(set)
    uunit, uperson = defaultdict(int), defaultdict(set)
    for _, who, _, _, cats, _, _ in rows:
        for c in cats:
            unit[c] += 1
            person[c].add(who)
            if c in CAUSE:
                up = '[차이의 원인 판단]'     # 문항 20-1 — 표 4-19에 넣지 않는다
            elif c.startswith('기존 서비스'):
                up = '[기존 서비스]'
            else:
                up = UP.get(c, '기타')
            uunit[up] += 1
            uperson[up].add(who)
    return unit, person, uunit, uperson


